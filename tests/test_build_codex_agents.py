"""End-to-end tests of scripts/build_codex_agents.py against a temporary home."""

import os
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts/build_codex_agents.py"
HEADER_PREFIX = "<!-- Generated by build_codex_agents.py"
CORE = "# Shared instructions\n\nThe core.\n"
LAYER = "# Personal layer\n\nThe layer.\n"


@pytest.fixture
def home(tmp_path: Path) -> Path:
    """A home with the core and the personal layer where Claude Code loads them, and no codex instructions yet."""
    home = tmp_path / "home"
    (home / ".claude/rules").mkdir(parents=True)
    (home / ".codex").mkdir()
    (home / ".claude/CLAUDE.md").write_text(CORE)
    (home / ".claude/rules/personal.md").write_text(LAYER)
    return home


def build(home: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), "personal"],
        env={**os.environ, "HOME": str(home)},
        capture_output=True,
        text=True,
        check=False,
    )


class TestBuildCodexAgents:
    def test_replaces_the_old_symlink_with_the_core_then_the_layer_under_a_header(self, home: Path) -> None:
        out = home / ".codex/AGENTS.md"
        out.symlink_to(home / ".claude/CLAUDE.md")

        result = build(home)

        assert result.returncode == 0, result.stderr
        assert not out.is_symlink()
        header, body = out.read_text().split("\n\n", 1)
        assert header.startswith(HEADER_PREFIX)
        assert "~/.claude/CLAUDE.md" in header
        assert "~/.claude/rules/personal.md" in header
        assert body == f"{CORE.rstrip()}\n\n{LAYER}"
        assert (home / ".claude/CLAUDE.md").read_text() == CORE
        assert out.stat().st_mode & 0o777 == 0o644
        assert [path.name for path in (home / ".codex").iterdir()] == ["AGENTS.md"]

    def test_rewrites_only_when_a_source_changed(self, home: Path) -> None:
        out = home / ".codex/AGENTS.md"
        assert build(home).returncode == 0
        first_inode = out.stat().st_ino

        assert build(home).returncode == 0

        assert out.stat().st_ino == first_inode
        (home / ".claude/rules/personal.md").write_text(LAYER + "\nA new rule.\n")
        assert build(home).returncode == 0
        assert out.read_text().endswith("A new rule.\n")

    def test_never_overwrites_a_hand_written_file(self, home: Path) -> None:
        out = home / ".codex/AGENTS.md"
        out.write_text("my own codex rules\n")

        result = build(home)

        assert result.returncode != 0
        assert out.read_text() == "my own codex rules\n"

    def test_a_missing_or_empty_source_stops_before_any_write(self, home: Path) -> None:
        layer = home / ".claude/rules/personal.md"
        core = home / ".claude/CLAUDE.md"
        layer.unlink()
        missing = build(home)
        layer.write_text(LAYER)
        core.write_text("\n")

        empty = build(home)

        assert missing.returncode != 0
        assert str(layer) in missing.stderr
        assert empty.returncode != 0
        assert str(core) in empty.stderr
        assert not (home / ".codex/AGENTS.md").exists()
