class TestCheckHistory:
    def test_fails_on_a_leak_in_any_branch_or_tag_that_a_later_commit_removed(
        self, repo: Path, fresh_home: Path
    ) -> None:
        write(repo / "notes.md", "nothing to see\n")
        commit(repo, "Add notes", "notes.md")
        subprocess.run(["git", "-C", str(repo), "switch", "-q", "-c", "side"], check=True)
        write(repo / "notes.md", "nothing to see\nbuilt for ExampleCorp\n")
