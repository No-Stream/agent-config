    def test_replace_moves_a_machine_from_one_shared_instructions_file_to_the_core_and_its_layer(
        self, repo: Path, tmp_path: Path
    ) -> None:
        home = tmp_path / "home-with-shared-file"
        write(home / "AGENTS.md", "the old shared instructions\n")
        for live in (".claude/CLAUDE.md", ".codex/AGENTS.md"):
            (home / live).parent.mkdir(parents=True)
            (home / live).symlink_to(home / "AGENTS.md")

        result = run_link_script(repo, home, "--replace", "--layer", "personal")

        assert result.returncode == 0, result.stderr
        assert (home / ".claude/CLAUDE.md").resolve() == (repo / "instructions/core.md").resolve()
