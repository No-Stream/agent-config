#!/usr/bin/env python3
"""Build ~/.codex/AGENTS.md from the shared core in ~/.claude/CLAUDE.md and one machine layer.

Usage: build_codex_agents.py LAYER, which joins ~/.claude/CLAUDE.md and ~/.claude/rules/LAYER.md. Codex reads a single
global instructions file and has no include syntax, so this script writes the core and the layer under a header naming
both, and only when the result changed. A symlink at the output path (such as an old link to CLAUDE.md) is replaced; a
regular file this script did not write is never overwritten. It uses only the standard library and stays
3.9-compatible, because cron, the link script and the git hook it installs run it under the system python3.
"""

import argparse
import logging
import os
import tempfile
from pathlib import Path

logger: logging.Logger = logging.getLogger(__name__)

CORE = Path(".claude/CLAUDE.md")
OUT = Path(".codex/AGENTS.md")
HEADER_PREFIX = "<!-- Generated by build_codex_agents.py"


def layer_path(layer: str) -> Path:
    return Path(".claude/rules") / f"{layer}.md"


def render(core_text: str, layer_text: str, layer: str) -> str:
    header = (
        f"{HEADER_PREFIX} from ~/{CORE} and ~/{layer_path(layer)}. Do not edit it by hand: edit those two files and "
        "rebuild with build_codex_agents.py. -->"
    )
    return f"{header}\n\n{core_text.rstrip()}\n\n{layer_text.rstrip()}\n"


def write_if_changed(out: Path, text: str) -> bool:
    """Write text to out in one rename unless out already holds it; refuse a hand-written regular file."""
    if out.exists() and not out.is_symlink():
        current = out.read_text(encoding="utf-8")
        if not current.startswith(HEADER_PREFIX):
            raise SystemExit(
                f"{out} is a regular file this script did not write; move it aside, then rerun"
            )
        if current == text:
            return False
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=out.parent, prefix=f".{out.name}.") as staging:
        staged = Path(staging) / out.name
        staged.write_text(text, encoding="utf-8")
        staged.chmod(0o644)
        os.replace(staged, out)
    return True


def build(home: Path, layer: str) -> bool:
    """Join home's core and layer into home's codex AGENTS.md; True when the file was written."""
    texts = []
    for source in (home / CORE, home / layer_path(layer)):
        if not source.is_file():
            raise SystemExit(f"{source} is missing; nothing was written")
        text = source.read_text(encoding="utf-8")
        if not text.strip():
            raise SystemExit(f"{source} is empty; nothing was written")
        texts.append(text)
    core_text, layer_text = texts
    return write_if_changed(home / OUT, render(core_text, layer_text, layer))


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "layer", help="the machine layer's name, such as personal for ~/.claude/rules/personal.md"
    )
    args = parser.parse_args()
    home = Path.home()
    if build(home, args.layer):
        logger.info("wrote %s", home / OUT)
    else:
        logger.info("unchanged: %s", home / OUT)


if __name__ == "__main__":
    main()
