#!/usr/bin/env python3
"""Build ~/.codex/AGENTS.md from the shared core in ~/.claude/CLAUDE.md and one machine layer.

Codex reads a single global instructions file and has no include syntax, so this script joins the core and the layer
under a header naming both, and writes the result only when it changed. A symlink at the output path (such as an old
link to CLAUDE.md) is replaced; a regular file this script did not write is never overwritten. It uses only the
standard library and stays 3.9-compatible, because scripts/link-repo-owned.sh runs it under the system python3.
"""

from __future__ import annotations

import argparse
import logging
import os
import tempfile
from pathlib import Path

logger: logging.Logger = logging.getLogger(__name__)

HEADER_PREFIX = "<!-- Generated by build_codex_agents.py"


def label(path: Path, home: Path) -> str:
    """The path in its ~/ form when it is under home, through either spelling of a symlinked home."""
    for prefix in sorted({str(home), str(home.resolve())}, key=len, reverse=True):
        if str(path).startswith(prefix + "/"):
            return "~" + str(path)[len(prefix) :]
    return str(path)


def render(core_text: str, layer_text: str, core_label: str, layer_label: str) -> str:
    assert core_text.strip() and layer_text.strip(), "the core and the layer must both have content"
    header = (
        f"{HEADER_PREFIX} from {core_label} and {layer_label}. Do not edit it by hand: edit those two files, "
        "then rerun build_codex_agents.py. -->"
    )
    return f"{header}\n\n{core_text.rstrip()}\n\n{layer_text.rstrip()}\n"


def write_if_changed(out: Path, text: str) -> bool:
    """Write text to out in one rename unless out already holds it; refuse a hand-written regular file."""
    if out.exists() and not out.is_symlink():
        current = out.read_text(encoding="utf-8")
        if not current.startswith(HEADER_PREFIX):
            raise SystemExit(f"{out} is a regular file this script did not write; move it aside, then rerun")
        if current == text:
            return False
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=out.parent, prefix=f".{out.name}.", delete=False) as handle:
        handle.write(text)
    os.chmod(handle.name, 0o644)
    os.replace(handle.name, out)
    return True


def build(core: Path, layer: Path, out: Path, home: Path) -> bool:
    for source in (core, layer):
        if not source.is_file():
            raise SystemExit(f"{source} is missing; nothing was written")
    text = render(
        core.read_text(encoding="utf-8"), layer.read_text(encoding="utf-8"), label(core, home), label(layer, home)
    )
    return write_if_changed(out, text)


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    home = Path.home()
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("layer", type=Path, help="the machine layer, such as ~/.claude/rules/personal.md")
    parser.add_argument("--core", type=Path, default=home / ".claude" / "CLAUDE.md")
    parser.add_argument("--out", type=Path, default=home / ".codex" / "AGENTS.md")
    args = parser.parse_args()
    if build(args.core, args.layer, args.out, home):
        logger.info("wrote %s", args.out)
    else:
        logger.info("unchanged: %s", args.out)


if __name__ == "__main__":
    main()
